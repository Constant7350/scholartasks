// Turns supabase/seed/colleges.json into supabase/seed/colleges.sql
// (insert or update every college; safe to run again).
//   node scripts/colleges/to-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";

const { fetched, rows } = JSON.parse(readFileSync("supabase/seed/colleges.json", "utf8"));
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || Number.isNaN(Number(v)) ? "null" : String(v));
const url = (v) => (!v ? "null" : q(/^https?:\/\//i.test(v) ? v : `https://${v}`));
const arr = (a) => `'{${a.map((x) => (x == null ? "NULL" : x)).join(",")}}'::int[]`;

const COLS = "id, name, city, state, url, price_calc_url, ownership, degree, size, admit_rate, sat_avg, act_mid, tuition_in, tuition_out, cost_attendance, avg_net_price, net_price, grad_rate, earnings, median_debt, programs, data_year";
const out = [`-- ${rows.length} colleges from the U.S. Department of Education College Scorecard, fetched ${fetched}.`, "-- Generated by scripts/colleges/to-sql.mjs. Safe to run again."];
for (let i = 0; i < rows.length; i += 250) {
  const chunk = rows.slice(i, i + 250).map((r) => `(${[
    n(r.id), q(r.name), q(r.city), q(r.state), url(r.url), url(r.calc), n(r.own), n(r.deg), n(r.size), n(r.adm), n(r.sat), n(r.act),
    n(r.tin), n(r.tout), n(r.coa), n(r.avgnet), arr(r.net), n(r.grad), n(r.earn), n(r.debt), q(JSON.stringify(r.prog)) + "::jsonb", q(fetched),
  ].join(", ")})`);
  out.push(`insert into colleges (${COLS}) values\n${chunk.join(",\n")}\non conflict (id) do update set ${COLS.split(", ").slice(1).map((c) => `${c} = excluded.${c}`).join(", ")}, updated_at = now();`);
}
writeFileSync("supabase/seed/colleges.sql", out.join("\n\n") + "\n");
console.log(`wrote ${rows.length} colleges`);
