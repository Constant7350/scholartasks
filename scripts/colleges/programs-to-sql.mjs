// Turns supabase/seed/college_programs.json into SQL:
//   supabase/seed/college_programs.sql          (everything, for a fresh database)
//   and, with an output folder, small parts to paste into the Supabase SQL editor:
//   node scripts/colleges/programs-to-sql.mjs [folder] [file-prefix]
// Safe to run again: each part replaces the rows it holds.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const { fetched, titles, summary, rows } = JSON.parse(readFileSync("supabase/seed/college_programs.json", "utf8"));
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || Number.isNaN(Number(v)) ? "null" : String(v));

const head = [
  `-- Majors at ${new Set(rows.map((r) => r[0])).size} colleges (${rows.length} programs) from the U.S. Department of Education College Scorecard, fetched ${fetched}.`,
  "-- Generated by scripts/colleges/programs-to-sql.mjs. Safe to run again.",
];
const names = ["insert into study_fields (cip, title) values",
  Object.entries(titles).sort().map(([c, t]) => `(${q(c)}, ${q(t)})`).join(",\n"),
  "on conflict (cip) do update set title = excluded.title;"].join("\n");
const national = ["insert into field_earnings (cip, level, programs, grads, earn_1yr, earn_4yr, debt) values",
  (summary ?? []).map((s) => `(${q(s[0])}, ${s.slice(1).map(n).join(", ")})`).join(",\n"),
  "on conflict (cip, level) do update set programs = excluded.programs, grads = excluded.grads, earn_1yr = excluded.earn_1yr, earn_4yr = excluded.earn_4yr, debt = excluded.debt;"].join("\n");

const COLS = "college_id, cip, level, grads, earn_1yr, earn_4yr, debt, online";
const insert = (chunk) => `insert into college_programs (${COLS}) values\n${chunk.map((r) =>
  `(${r[0]},'${r[1]}',${r[2]},${r[3]},${n(r[4])},${n(r[5])},${n(r[6])},${r[7] ? "true" : "false"})`).join(",\n")}\n` +
  `on conflict (college_id, cip, level) do update set grads = excluded.grads, earn_1yr = excluded.earn_1yr, earn_4yr = excluded.earn_4yr, debt = excluded.debt, online = excluded.online;`;

const bodies = [];
for (let i = 0; i < rows.length; i += 1000) bodies.push(insert(rows.slice(i, i + 1000)));
writeFileSync("supabase/seed/college_programs.sql", [...head, names, national, ...bodies].join("\n\n") + "\n");
console.log(`wrote supabase/seed/college_programs.sql: ${rows.length} programs`);

const [dir, prefix = "majors"] = process.argv.slice(2);
if (dir) {
  // Parts under about 600 KB each so the Supabase SQL editor takes them.
  const parts = [];
  let cur = [];
  let size = 0;
  for (const b of bodies) {
    if (size + b.length > 600_000 && cur.length) { parts.push(cur); cur = []; size = 0; }
    cur.push(b); size += b.length;
  }
  if (cur.length) parts.push(cur);
  parts.forEach((p, i) => {
    const file = join(dir, `${prefix}-part${i + 1}.sql`);
    const first = i === 0 ? [names, national] : [];
    writeFileSync(file, [`-- ScholarTasks: majors data, part ${i + 1} of ${parts.length}. Run after the update that creates the college_programs table. Safe to run twice.`, ...head.slice(0, 1), ...first, ...p].join("\n\n") + "\n");
    console.log(`wrote ${file}`);
  });
}
