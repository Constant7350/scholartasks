// Turns supabase/seed/college_faith.json into supabase/seed/college_faith.sql:
// sets colleges.religious_affiliation (Scorecard code) for every college that
// reports one, and clears it for the rest. Safe to run again.
//   node scripts/colleges/faith-to-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";

const { fetched, faith } = JSON.parse(readFileSync("supabase/seed/college_faith.json", "utf8"));
const pairs = Object.entries(faith).map(([id, code]) => `(${Number(id)}, ${Number(code)})`);
const sql = [
  `-- Religious affiliation of ${pairs.length} colleges from the U.S. Department of Education College Scorecard, fetched ${fetched}.`,
  "-- Generated by scripts/colleges/faith-to-sql.mjs. Safe to run again.",
  "update colleges set religious_affiliation = null where religious_affiliation is not null;",
  `update colleges c set religious_affiliation = v.code from (values\n${pairs.join(",\n")}\n) as v(id, code) where c.id = v.id;`,
].join("\n\n") + "\n";
writeFileSync("supabase/seed/college_faith.sql", sql);
console.log(`wrote supabase/seed/college_faith.sql: ${pairs.length} colleges`);
